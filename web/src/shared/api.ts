// Cache for the per-extension collection JSON loaded once in static mode (build_spa_collection).
const collectionCache = new Map<string, Promise<unknown>>();
async function loadCollection<T>(segment: string): Promise<T[]> {
  const hit = collectionCache.get(segment);
  if (hit) return hit as Promise<T[]>;
  const p = apiFetch<T[]>(`/${segment}`);
  collectionCache.set(segment, p);
  return p;
}

export async function fetchBlogPosts(): Promise<BlogPost[]> {
  return (await loadBlogData()).posts;
}
export async function fetchBlogPost(slug: string): Promise<BlogPost> {
  const posts = await fetchBlogPosts();
  const post = posts.find((p) => p.slug === slug);
  if (!post) throw new ApiError(404, `blog post not found: ${slug}`);
  return post;
}
export async function fetchBlogSeries(): Promise<BlogSeries[]> {
  if (import.meta.env.VITE_DATA_MODE === 'static') return (await loadBlogData()).series;
  return apiFetch<BlogSeries[]>('/blog/series');
}
export async function fetchBlogSeriesBySlug(slug: string): Promise<BlogSeriesDetail> {
  if (import.meta.env.VITE_DATA_MODE === 'static') {
    const series = (await loadBlogData()).series.find((s) => s.slug === slug);
    if (!series) throw new ApiError(404, `blog series not found: ${slug}`);
    const posts = (await fetchBlogPosts())
      .filter((p) => p.series_id === series.id)
      .sort((a, b) => (a.series_order ?? 1e15) - (b.series_order ?? 1e15));
    return { ...series, posts };
  }
  return apiFetch<BlogSeriesDetail>(`/blog/series/${encodeURIComponent(slug)}`);
}
export const fetchProjects = () => apiFetch<Project[]>('/projects');
// In static mode, /data/projects.json holds `Project[]` (no screenshots). Static-mode
// projects have no screenshots in the v2 SSG; live mode returns `ProjectDetail` with
// screenshots from the API. (Adding screenshots to the SSG is a follow-up.)
export async function fetchProject(slug: string): Promise<ProjectDetail> {
  if (import.meta.env.VITE_DATA_MODE === 'static') {
    // The build emits a collection-only /data/projects.json (no per-item file, no screenshots
    // in the v2 SSG — see ext-projects build_data). Resolve the detail from the collection.
    const projects = await loadCollection<Project>('projects');
    const p = projects.find((x) => x.slug === slug);
    if (!p) throw new ApiError(404, `project not found: ${slug}`);
    return { ...p, screenshots: [] };
  }
  return apiFetch<ProjectDetail>(`/projects/${slug}`);
}
