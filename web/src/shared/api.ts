// In static mode, load /data/search-index.json once and substring-filter by `q`.
// ~1k docs at ~200 bytes each = ~200KB; substring filter is sub-millisecond.
export async function searchAll(q: string, lang?: 'ko' | 'en'): Promise<SearchHit[]> {
  if (import.meta.env.VITE_DATA_MODE === 'static') {
    const docs = await loadCollection<SearchHit>('search-index');
    const needle = q.trim().toLowerCase();
    if (!needle) return docs;
    return docs.filter(
      (d) =>
        d.title.toLowerCase().includes(needle) ||
        d.snippet.toLowerCase().includes(needle),
    );
  }
  return apiFetch<SearchHit[]>(
    `/search?q=${encodeURIComponent(q)}${lang ? `&lang=${lang}` : ''}`,
  );
}

